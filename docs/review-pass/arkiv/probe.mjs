import { createPublicClient } from '@arkiv-network/sdk';
import { tiramisu } from '@arkiv-network/sdk/chains';
import { ExpirationTime } from '@arkiv-network/sdk/utils';
import { eq, gt, render } from '@arkiv-network/sdk/query';
import { u64 } from '@arkiv-network/sdk/attr';
import { http, webSocket } from 'viem';
import { writeFile } from 'node:fs/promises';
const started = new Date().toISOString();
const rpcUrl = 'https://rpc.tiramisu.db-chain.testnet.arkiv.network';
const read = createPublicClient({chain:tiramisu,transport:http(rpcUrl,{retryCount:0,timeout:12000})});
const predicate = [eq('application','review-pass'),eq('kind','assignment'),eq('taskClass','technical-review'),eq('qualificationClass','7'),eq('settlementChain',43113),gt('acceptBefore',u64(1789200000n))];
const chainId = await read.getChainId();
const timing = await read.getBlockTiming();
let page = await read.select({key:true,owner:true,expiresAt:true}).where(...predicate).limit(100).fetch();
let count=page.entities.length,pages=1;
while(page.hasNextPage()){page=await page.next();count+=page.entities.length;pages++;}
const durations = [5,6,30,60].map(seconds=>{try {return {seconds,blocks:String(ExpirationTime.fromSeconds(seconds).minLifetime),status:'accepted'};}catch(e){return {seconds,status:'rejected',error:e.name};}});
const live = createPublicClient({chain:tiramisu,transport:webSocket(rpcUrl.replace('https:','wss:'),{reconnect:{attempts:3,delay:500},keepAlive:false})});
let events=0,heads=0,errors=0,phase='before-drop';const log=[];
const unwatch=live.watchEntityEvents({onEvent:e=>{events++;log.push({kind:'entity',phase,type:e.type,block:String(e.blockNumber)});},onError:()=>{errors++;}});
const unheads=live.watchBlockNumber({poll:false,onBlockNumber:b=>{heads++;log.push({kind:'head',phase,block:String(b)});},onError:()=>{errors++;}});
const client=await live.transport.getRpcClient();
await new Promise(r=>setTimeout(r,7000));
const before={events,heads,subscriptions:client.subscriptions.size};
phase='after-drop';client.socket.close();
await new Promise(r=>setTimeout(r,8000));
const after={events:events-before.events,heads:heads-before.heads,subscriptions:client.subscriptions.size};
unwatch();unheads();client.close();
const output={observedAt:started,readOnly:true,writes:0,chainId,timing,queryPredicates:predicate.map(render),queryPages:pages,queryCount:count,durations,webSocket:{transport:live.transport.type,fromBlock:false,forcedSocketClose:true,before,after,errors,log},nativeExpiry:'not tested; no entity written',twoWalletDemo:'not tested'};
const json=JSON.stringify(output,(_,v)=>typeof v==='bigint'?String(v):v,2)+'\n';
await writeFile(new URL('./probe-evidence.json',import.meta.url),json);console.log(json);
